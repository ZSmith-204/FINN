    def test_force_reports_created_false_and_replaces_atomically(self):
        with tempfile.TemporaryDirectory() as tmp:
            self.assertEqual(
                run_cli(["init", tmp, "--template", "example"])[0], 0
            )
            target = os.path.join(tmp, "finn.json")
            with open(target, "r", encoding="utf-8") as handle:
                first_text = handle.read()

            code, stdout, _ = run_cli(
                [
                    "init",
                    tmp,
                    "--template",
                    "minimal",
                    "--name",
                    "Second",
                    "--force",
                    "--json",
                ]
            )
            self.assertEqual(code, 0)
            document = json.loads(stdout)
            self.assertEqual(document["created"], False)
            self.assertEqual(document["template"], "minimal")
            self.assertEqual(document["path"], "finn.json")
            self.assertTrue(document["ok"])


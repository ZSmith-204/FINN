def run_cli(argv):
    """Invoke ``cli.main`` and capture its streams."""

    stdout = io.StringIO()
    stderr = io.StringIO()
    with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
        code = cli.main(list(argv))
    return code, stdout.getvalue(), stderr.getvalue()


class EnvIsolatedTestCase(unittest.TestCase):
    """Remove ambient FINN_CONFIG/FINN_DB_PATH for the duration of each test."""

    def setUp(self):
        super().setUp()
        patcher = mock.patch.dict(os.environ, {}, clear=False)
        patcher.start()
        self.addCleanup(patcher.stop)
        for name in ("FINN_CONFIG", "FINN_DB_PATH"):
            os.environ.pop(name, None)


def write_config(directory, config, name="finn.json"):
    path = os.path.join(directory, name)
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(config, handle)
    return path


def base_config(**overrides):
    config = {
        "version": 1,
        "database": {
            "file": "finn.db",
            "tables": {
                "users": {
                    "columns": {
                        "id": {
                            "type": "integer",
                            "primaryKey": True,
                            "autoincrement": True,
                        },
                        "name": {"type": "text"},
                    }
                }
            },
        },
        "api": {
            "basePath": "/api",
            "endpoints": {"/users": {"get": "SELECT * FROM users"}},
        },
    }
    config.update(overrides)
    return config


class JsonTests(EnvIsolatedTestCase):
    def test_line_comments_are_rejected(self):
        value, span = cli.parse_json('{"a": 1} // a line comment')
        self.assertIsNone(value)
        self.assertIsNotNone(span)

    def test_block_comments_are_rejected(self):
        value, span = cli.parse_json('{"a": 1 /* a block comment */}')
        self.assertIsNone(value)
        self.assertIsNotNone(span)

    def test_trailing_commas_are_rejected(self):
        value, span = cli.parse_json('{"a": 1,}')
        self.assertIsNone(value)
        self.assertIsNotNone(span)

    def test_comment_markers_inside_strings_are_preserved(self):
        text = (
            '{"url": "http://example.com//x",'
            ' "sql": "SELECT \'/*\' AS marker",'
            ' "quote": "a \\"//\\" b"}'
        )
        value = cli.load_json(text)
        self.assertEqual(value["url"], "http://example.com//x")
        self.assertEqual(value["sql"], "SELECT '/*' AS marker")
        self.assertEqual(value["quote"], 'a "//" b')

    def test_single_quotes_are_rejected(self):
        text = "{'sql': 'SELECT ''x'' AS y'}"
        value, span = cli.parse_json(text)
        self.assertIsNone(value)
        self.assertIsNotNone(span)

    def test_bom_is_tolerated(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "finn.json")
            with open(path, "wb") as handle:
                handle.write(
                    b"\xef\xbb\xbf" + json.dumps(base_config()).encode("utf-8")
                )
            code, _, stderr = run_cli(["validate", "--config", path])
            self.assertEqual(code, 0, stderr)

    def test_parse_error_has_span(self):
        value, span = cli.parse_json('{"a": }')
        self.assertIsNone(value)
        self.assertIsNotNone(span)
        self.assertGreater(span["line"], 0)
        self.assertGreater(span["column"], 0)



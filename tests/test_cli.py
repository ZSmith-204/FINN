class BuildTests(EnvIsolatedTestCase):
    def test_build_emits_artifacts_and_manifest(self):
        with tempfile.TemporaryDirectory() as tmp:
            self.assertEqual(run_cli(["init", tmp])[0], 0)
            config_path = os.path.join(tmp, "finn.json")
            out_dir = os.path.join(tmp, "build")

            code, stdout, _ = run_cli(
                ["build", "--config", config_path, "--out", out_dir]
            )
            self.assertEqual(code, 0)
            self.assertIn("Built", stdout)

            for name in (
                "main.py",
                "API.py",
                "DB.py",
                "finn.db",
                ".finn-build.json",
            ):
                self.assertTrue(
                    os.path.isfile(os.path.join(out_dir, name)), name
                )

            with open(
                os.path.join(out_dir, ".finn-build.json"),
                "r",
                encoding="utf-8",
            ) as handle:
                manifest = json.load(handle)

            self.assertEqual(manifest["finnVersion"], cli.FINN_VERSION)
            self.assertIn("configSha256", manifest)
            self.assertIn("builtAt", manifest)
            self.assertEqual(len(manifest["artifacts"]), 4)
            self.assertEqual(
                [record["file"] for record in manifest["artifacts"]],
                ["main.py", "API.py", "DB.py", "finn.db"],
            )
            self.assertEqual(manifest["db"]["file"], "finn.db")
            self.assertTrue(manifest["db"]["created"])

    def test_rebuild_is_idempotent_and_init_does_not_rerun(self):
        with tempfile.TemporaryDirectory() as tmp:
            config = {
                "version": 1,
                "database": {
                    "file": "finn.db",
                    "tables": {
                        "users": {
                            "columns": {
                                "id": {
                                    "type": "integer",
                                    "primaryKey": True,
                                    "autoincrement": True,
                                },
                                "name": {"type": "text"},
                            }
                        }
                    },
                    "init": [
                        "INSERT INTO users (name) VALUES ('Ada')",
                        "INSERT INTO users (name) VALUES ('Grace')",
                    ],
                },
                "api": {"endpoints": {"/users": {"get": "SELECT * FROM users"}}},
            }
            path = write_config(tmp, config)
            out_dir = os.path.join(tmp, "build")

            self.assertEqual(
                run_cli(
                    ["build", "--config", path, "--out", out_dir]
                )[0],
                0,
            )
            db_path = os.path.join(out_dir, "finn.db")
            with sqlite3.connect(db_path) as connection:
                first = connection.execute(
                    "SELECT COUNT(*) FROM users"
                ).fetchone()[0]
            self.assertEqual(first, 2)

            self.assertEqual(
                run_cli(
                    ["build", "--config", path, "--out", out_dir]
                )[0],
                0,
            )
            with open(
                os.path.join(out_dir, ".finn-build.json"),
                "r",
                encoding="utf-8",
            ) as handle:
                manifest = json.load(handle)
            self.assertFalse(manifest["db"]["created"])

            with sqlite3.connect(db_path) as connection:
                second = connection.execute(
                    "SELECT COUNT(*) FROM users"
                ).fetchone()[0]
            self.assertEqual(second, 2)


def _free_port():
    probe = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        probe.bind(("127.0.0.1", 0))
        return probe.getsockname()[1]
    finally:
        probe.close()


class RunServerTests(EnvIsolatedTestCase):
    """End-to-end ``run`` coverage (acceptance criteria 7/8, cli-layer.md §7)."""

    @unittest.skipUnless(HAVE_SERVER, "uvicorn and fastapi are not installed")
    def test_run_serves_healthz_and_stops_cleanly(self):
        with tempfile.TemporaryDirectory() as tmp:
            config_path = write_config(tmp, base_config())
            port = _free_port()
            process = subprocess.Popen(
                [
                    sys.executable,
                    "finn_cli.py",
                    "run",
                    "--json",
                    "--config",
                    config_path,
                    "--port",
                    str(port),
                ],
                cwd=REPO_ROOT,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
                text=True,
            )
            events = []
            stdout_lines = []
            non_ndjson = []
            lock = threading.Lock()

            def _reader():
                for line in process.stdout:
                    line = line.strip()
                    if not line:
                        continue
                    with lock:
                        stdout_lines.append(line)
                    try:
                        event = json.loads(line)
                    except ValueError:
                        with lock:
                            non_ndjson.append(line)
                        continue
                    if isinstance(event, dict) and "event" in event:
                        with lock:
                            events.append(event)
                    else:
                        with lock:
                            non_ndjson.append(line)

            reader = threading.Thread(target=_reader, daemon=True)
            reader.start()

            def _snapshot():
                with lock:
                    return list(events)

            def _wait_event(name, timeout=45.0):
                deadline = time.monotonic() + timeout
                while time.monotonic() < deadline:
                    for event in _snapshot():
                        if event.get("event") == name:
                            return event
                    if process.poll() is not None:
                        time.sleep(0.2)
                        for event in _snapshot():
                            if event.get("event") == name:
                                return event
                        return None
                    time.sleep(0.1)
                return None

            try:
                listening = _wait_event("listening")
                self.assertIsNotNone(
                    listening,
                    "no listening event; got {!r}".format(_snapshot()),
                )
                self.assertEqual(listening["host"], "127.0.0.1")
                self.assertEqual(listening["port"], port)
                self.assertIsInstance(listening["pid"], int)

                event_names = [event.get("event") for event in _snapshot()]
                self.assertIn("building", event_names)
                self.assertIn("build_ok", event_names)

                status = None
                deadline = time.monotonic() + 20
                while time.monotonic() < deadline:
                    try:
                        with urllib.request.urlopen(
                            "http://127.0.0.1:{}/healthz".format(port),
                            timeout=5,
                        ) as response:
                            status = response.status
                            response.read()
                        break
                    except OSError:
                        time.sleep(0.2)
                self.assertEqual(status, 200)

                process.send_signal(signal.SIGTERM)
                self.assertEqual(process.wait(timeout=30), 0)

                stopped = _wait_event("stopped", timeout=10)
                self.assertIsNotNone(
                    stopped, "no stopped event; got {!r}".format(_snapshot())
                )
                self.assertEqual(stopped["exitCode"], 0)

                reader.join(timeout=10)
                with lock:
                    bad_lines = list(non_ndjson)
                    seen_lines = list(stdout_lines)
                self.assertTrue(seen_lines, "expected NDJSON events on stdout")
                self.assertEqual(
                    bad_lines,
                    [],
                    "stdout must be strict NDJSON (cli-layer.md §7); "
                    "non-conforming lines: {!r}".format(bad_lines),
                )
            finally:
                if process.poll() is None:
                    process.kill()
                    process.wait()
                reader.join(timeout=5)
                process.stdout.close()



def validate_structure(root):
    """Top-level structural validation (docs/cli-spec.md §6.2 stage 2)."""

    diagnostics = []
    if not isinstance(root, dict):
        diagnostics.append(
            _error(
                "FINN-E0021",
                "structural",
                None,
                "top-level JSON value must be an object",
            )
        )
        return diagnostics

    if "version" not in root:
        diagnostics.append(
            _error(
                "FINN-E0021",
                "structural",
                "version",
                "is required",
                hint='add "version": 1',
            )
        )
    else:
        version = root["version"]
        if isinstance(version, bool) or not isinstance(version, int) or version != CONFIG_SCHEMA:
            diagnostics.append(
                _error(
                    "FINN-E0021",
                    "structural",
                    "version",
                    "must be the integer 1 (config schema version)",
                    hint='set "version": 1',
                )
            )

    if "meta" in root and not isinstance(root["meta"], dict):
        diagnostics.append(
            _error(
                "FINN-E0021",
                "structural",
                "meta",
                "must be a JSON object",
            )
        )

    for key in ("database", "api"):
        if key not in root:
            diagnostics.append(
                _error(
                    "FINN-E0021",
                    "structural",
                    key,
                    "is required and must be a JSON object",
                    hint='add a "{}" object'.format(key),
                )
            )
        elif not isinstance(root[key], dict):
            diagnostics.append(
                _error(
                    "FINN-E0021",
                    "structural",
                    key,
                    "must be a JSON object",
                )
            )

    ignore_extra = (
        isinstance(root.get("meta"), dict)
        and root["meta"].get("extraKeys") == "ignore"
    )
    if not ignore_extra:
        for key in root:
            if key not in _TOP_LEVEL_KEYS:
                diagnostics.append(
                    _error(
                        "FINN-E0021",
                        "structural",
                        key,
                        "unknown top-level key {!r}".format(key),
                        hint=(
                            "remove it, or set meta.extraKeys to \"ignore\" "
                            "to allow extra keys"
                        ),
                    )
                )
    return diagnostics


def _semantic_diagnostics(config):
    """Run ``parse_database``/``parse_api`` and collect warnings."""

    diagnostics = []
    db_spec = None
    api_spec = None

    if isinstance(config.get("database"), dict):
        try:
            db_spec = parse_database(config["database"])
        except ConfigError as exc:
            diagnostics.append(
                _error("FINN-E0031", "semantic", exc.path, exc.message)
            )

    if isinstance(config.get("api"), dict):
        try:
            api_spec = parse_api(config["api"])
        except ConfigError as exc:
            diagnostics.append(
                _error("FINN-E0031", "semantic", exc.path, exc.message)
            )

    raw_api = config.get("api")
    if isinstance(raw_api, dict) and isinstance(raw_api.get("endpoints"), dict):
        for path, endpoint in raw_api["endpoints"].items():
            if not isinstance(endpoint, dict):
                continue
            lowered = {str(key).lower() for key in endpoint}
            if "head" in lowered or "options" in lowered:
                diagnostics.append(
                    _warning(
                        "FINN-W0002",
                        "semantic",
                        "api.endpoints.{}".format(path),
                        "head/options operation declared but ignored "
                        "(FastAPI derives these from get)",
                        hint="remove the head/options key",
                    )
                )

    if api_spec is not None:
        for path, endpoint in api_spec.endpoints.items():
            for method, operation in endpoint.operations.items():
                kind = statement_kind(operation.sql)
                mismatch = (
                    (kind == "INSERT" and method != "post")
                    or (kind == "UPDATE" and method not in ("put", "patch"))
                    or (kind == "DELETE" and method != "delete")
                    or (kind == "SELECT" and method == "delete")
                )
                if mismatch:
                    diagnostics.append(
                        _warning(
                            "FINN-W0003",
                            "semantic",
                            "api.endpoints.{}.{}".format(path, method),
                            "{} operation is bound to a {} statement".format(
                                method.upper(), kind
                            ),
                            hint="bind the statement to a matching HTTP method",
                        )
                    )

    return db_spec, api_spec, diagnostics


def _stage_config(config_path):
    """Run stages 1-3 (read, parse, structural, semantic)."""

    result = {
        "config": config_path,
        "raw": None,
        "value": None,
        "db_spec": None,
        "api_spec": None,
        "diagnostics": [],
        "exit_code": 1,
    }

    try:
        with open(config_path, "rb") as handle:
            raw = handle.read()
    except OSError as exc:
        result["diagnostics"].append(
            _error(
                "FINN-E0041",
                "build",
                config_path,
                "cannot read config file: {}".format(exc),
            )
        )
        result["exit_code"] = 2
        return result

    result["raw"] = raw
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        result["diagnostics"].append(
            _error(
                "FINN-E0012",
                "parse",
                None,
                "config is not valid UTF-8: {}".format(exc),
            )
        )
        return result

    try:
        value = load_json(text)
    except json.JSONDecodeError as exc:
        result["diagnostics"].append(
            _error(
                "FINN-E0012",
                "parse",
                None,
                "JSON parse error: {}".format(exc.msg),
                span={"line": exc.lineno, "column": exc.colno},
            )
        )
        return result

    result["value"] = value
    diagnostics = validate_structure(value)
    result["diagnostics"].extend(diagnostics)
    if _has_errors(diagnostics):
        result["exit_code"] = 1
        return result

    db_spec, api_spec, semantic = _semantic_diagnostics(value)
    result["diagnostics"].extend(semantic)
    result["db_spec"] = db_spec
    result["api_spec"] = api_spec
    result["exit_code"] = 1 if _has_errors(semantic) else 0
    return result



def load_json(text):
    """Parse strict JSON text; raises :class:`json.JSONDecodeError` on failure.

    Callers are responsible for decoding the raw bytes as UTF-8 and tolerating
    a BOM (``utf-8-sig``); this helper performs no comment or trailing-comma
    tolerance.
    """

    return json.loads(text)


def parse_json(text):
    """Return ``(value, span)``; ``span`` is non-null when parsing fails."""

    try:
        return load_json(text), None
    except json.JSONDecodeError as exc:
        return None, {"line": exc.lineno, "column": exc.colno}



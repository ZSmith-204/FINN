def _render_template(template, name=None):
    if template not in _TEMPLATES:
        raise ValueError("unknown template {!r}".format(template))
    body = _TEMPLATES[template]
    if name is not None:
        literal = json.dumps(name, ensure_ascii=False)
        if template == "blank":
            body = body.replace(
                '  "meta": {},', '  "meta": {{"name": {}}},'.format(literal), 1
            )
        else:
            body = body.replace(
                '  "version": 1,\n',
                '  "version": 1,\n  "meta": {{"name": {}}},\n'.format(literal),
                1,
            )
    return body


def _cmd_init(args):
    target = os.path.abspath(args.target) if args.target else os.getcwd()
    target_config = os.path.join(target, "finn.json")

    if os.path.exists(target_config) and not args.force:
        diagnostic = _error(
            "FINN-E0061",
            "build",
            target_config,
            "{} already exists; refusing to overwrite".format(
                os.path.basename(target_config)
            ),
            hint="--force",
        )
        if args.json:
            _emit_json({"ok": False, "diagnostics": [diagnostic]})
        else:
            _print_diagnostics([diagnostic], sys.stderr)
        return 2

    created = not os.path.exists(target_config)
    tmp_path = None
    try:
        os.makedirs(target, exist_ok=True)
        text = _render_template(args.template, args.name)
        descriptor, tmp_path = tempfile.mkstemp(
            dir=target, prefix=".finn.json.", suffix=".tmp"
        )
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp_path, target_config)
        tmp_path = None
    except OSError as exc:
        if tmp_path is not None:
            try:
                os.unlink(tmp_path)
            except OSError:
                pass
        diagnostic = _error(
            "FINN-E0041",
            "build",
            target_config,
            "cannot write config file: {}".format(exc),
        )
        if args.json:
            _emit_json({"ok": False, "diagnostics": [diagnostic]})
        else:
            _print_diagnostics([diagnostic], sys.stderr)
        return 2

    if args.json:
        _emit_json(
            {
                "ok": True,
                "template": args.template,
                "path": "finn.json",
                "created": created,
            }
        )
    else:
        _print_init_next_steps(args.template)
    return 0


def _requirements_path():
    """Absolute path to the requirements.txt bundled next to this CLI."""
    return os.path.join(
        os.path.dirname(os.path.realpath(__file__)), REQUIREMENTS_FILENAME
    )


def _requirements_display_path():
    """Requirements path rendered runnable relative to the current directory."""
    req_path = _requirements_path()
    try:
        return os.path.relpath(req_path)
    except ValueError:  # pragma: no cover - different drives (Windows)
        return req_path


def _prompt_allowed():
    """Whether ``init`` may offer the interactive dependency prompt.

    Requires both stdin and stdout to be real terminals so a piped or
    scripted ``finn init`` (and the test harness, which redirects stdout to
    an in-memory buffer) never blocks waiting for keyboard input.
    """
    stdin_isatty = getattr(sys.stdin, "isatty", None)
    stdout_isatty = getattr(sys.stdout, "isatty", None)
    try:
        return bool(
            stdin_isatty and stdout_isatty and stdin_isatty() and stdout_isatty()
        )
    except (AttributeError, ValueError, OSError, TypeError):  # pragma: no cover - defensive
        return False


def _install_dependencies(req_path):
    """Run ``python -m pip install -r <req_path>`` in the active interpreter.

    Uses ``sys.executable`` so packages land in the environment running FINN
    (e.g. an active virtualenv), never the system Python. Returns True when
    pip reports success.
    """
    try:
        result = subprocess.run(
            [sys.executable, "-m", "pip", "install", "-r", req_path]
        )
    except OSError as exc:
        sys.stderr.write("cannot launch pip: {}\n".format(exc))
        sys.stderr.flush()
        return False
    return result.returncode == 0


def _prompt_install(req_path):
    """Interactively offer to install dependencies (called only when allowed)."""
    try:
        answer = input(
            "Install dependencies from {} now? [y/N]: ".format(
                _requirements_display_path()
            )
        )
    except (EOFError, KeyboardInterrupt):
        return
    if answer.strip().lower() in ("y", "yes"):
        sys.stdout.write("Installing dependencies...\n")
        sys.stdout.flush()
        if not _install_dependencies(req_path):
            sys.stderr.write(
                "dependency installation failed; re-run "
                "'{} -m pip install -r {}' later\n".format(
                    sys.executable, _requirements_display_path()
                )
            )
            sys.stderr.flush()


def _print_init_next_steps(template):
    """Human-mode ``init`` output, including the dependency install hint."""
    req_path = _requirements_path()
    have_reqs = os.path.isfile(req_path)

    sys.stdout.write("Wrote finn.json (template: {})\n".format(template))
    steps = ["finn build", "finn run"]
    if have_reqs:
        steps.insert(0, "pip install -r {}".format(_requirements_display_path()))
    sys.stdout.write("Next steps:\n")
    for step in steps:
        sys.stdout.write("  {}\n".format(step))
    sys.stdout.flush()

    if have_reqs and _prompt_allowed():
        _prompt_install(req_path)


def _cmd_build(args):
    start = time.monotonic()
    config_path, discovery = resolve_config(args.config, args.config_path)
    duration_ms = int(round((time.monotonic() - start) * 1000))
    if config_path is None:
        _emit_failure(discovery, args.json, duration_ms=duration_ms)
        return _exit_code(discovery)

    if args.out:
        out_dir = os.path.abspath(args.out)
    else:
        out_dir = os.path.join(
            os.path.dirname(os.path.abspath(config_path)), "build"
        )

    result = _execute_build(config_path, out_dir)
    result["diagnostics"] = discovery + result["diagnostics"]
    duration_ms = int(round((time.monotonic() - start) * 1000))

    if not result["ok"]:
        _emit_failure(
            result["diagnostics"],
            args.json,
            config_path=config_path,
            out_dir=out_dir,
            duration_ms=duration_ms,
        )
        return result["exit_code"]

    if args.json:
        _emit_json(
            _build_json_document(result, config_path, out_dir, duration_ms)
        )
    else:
        warnings = [
            diagnostic
            for diagnostic in result["diagnostics"]
            if diagnostic.get("severity") != "error"
        ]
        if warnings:
            _print_diagnostics(warnings, sys.stderr)
        if not args.quiet:
            _print_summary(result, config_path, out_dir, duration_ms)
    return 0


def _cmd_validate(args):
    config_path, discovery = resolve_config(args.config, args.config_path)
    if config_path is None:
        diagnostics = discovery
        if args.json:
            _emit_json({"ok": False, "diagnostics": diagnostics})
        else:
            _print_diagnostics(diagnostics, sys.stderr)
        return _exit_code(diagnostics)

    stages = _stage_config(config_path)
    diagnostics = discovery + stages["diagnostics"]
    ok = not _has_errors(diagnostics)
    if args.json:
        _emit_json({"ok": ok, "diagnostics": diagnostics})
    else:
        _print_diagnostics(diagnostics, sys.stderr)
    return _exit_code(diagnostics)


def _read_manifest(out_dir):
    path = os.path.join(out_dir, ".finn-build.json")
    try:
        with open(path, "r", encoding="utf-8") as handle:
            value = json.load(handle)
    except (OSError, ValueError):
        return None
    return value if isinstance(value, dict) else None


def _is_stale(manifest, config_sha256):
    """Return whether a build must be regenerated (docs/cli-spec.md §6.3)."""

    if not isinstance(manifest, dict):
        return True
    return (
        manifest.get("configSha256") != config_sha256
        or manifest.get("finnVersion") != FINN_VERSION
    )


def _read_bytes(path):
    with open(path, "rb") as handle:
        return handle.read()


def _check_port(host, port):
    """Bind a socket to ``(host, port)``; return an E0051 diagnostic on failure."""

    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        sock.bind((host, port))
    except OSError as exc:
        return _error(
            "FINN-E0051",
            "runtime",
            None,
            "cannot bind {}:{}: {}".format(host, port, exc),
            hint="choose another --port",
        )
    finally:
        sock.close()
    return None


def _can_connect(host, port):
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.settimeout(0.25)
    try:
        return sock.connect_ex((host, port)) == 0
    except OSError:
        return False
    finally:
        sock.close()


def _wait_for_port(host, port, process, timeout=10.0):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if process.poll() is not None:
            return False
        if _can_connect(host, port):
            return True
        time.sleep(0.1)
    return False


def _print_banner(host, port, pid):
    base = "http://{}:{}".format(host, port)
    sys.stdout.write(
        "FINN dev server\n"
        "  App:     {base}\n"
        "  Docs:    {base}/docs\n"
        "  Redoc:   {base}/redoc\n"
        "  Health:  {base}/healthz\n"
        "  PID:     {pid}\n"
        "  Config changes require a restart (no hot reload in v1).\n"
        "  Standalone: uvicorn build.main:app\n".format(
            base=base, pid=pid
        )
    )
    sys.stdout.flush()


def _run_errors(diagnostics, json_mode):
    if json_mode:
        errors = [
            diagnostic
            for diagnostic in diagnostics
            if diagnostic.get("severity") == "error"
        ] or diagnostics
        for diagnostic in errors:
            _emit_event({"event": "error", "diagnostic": diagnostic})
    else:
        _print_diagnostics(diagnostics, sys.stderr)


def _terminate_child(process):
    if process.poll() is not None:
        return
    process.terminate()
    try:
        process.wait(timeout=5)
    except subprocess.TimeoutExpired:
        process.kill()
        process.wait()


def _cmd_run(args):
    config_path, discovery = resolve_config(args.config, args.config_path)
    if config_path is None:
        _run_errors(discovery, args.json)
        return _exit_code(discovery)

    out_dir = os.path.join(
        os.path.dirname(os.path.abspath(config_path)), "build"
    )

    try:
        raw = _read_bytes(config_path)
    except OSError as exc:
        diagnostic = _error(
            "FINN-E0041",
            "build",
            config_path,
            "cannot read config file: {}".format(exc),
        )
        _run_errors([diagnostic], args.json)
        return 2

    config_sha = hashlib.sha256(raw).hexdigest()

    if args.no_build:
        main_path = os.path.join(out_dir, "main.py")
        manifest_path = os.path.join(out_dir, ".finn-build.json")
        if not os.path.isfile(main_path) or not os.path.isfile(manifest_path):
            diagnostic = _error(
                "FINN-E0041",
                "build",
                out_dir,
                "build output is missing; cannot use --no-build",
                hint="run 'finn build' first",
            )
            _run_errors([diagnostic], args.json)
            return 2
    else:
        manifest = _read_manifest(out_dir)
        if _is_stale(manifest, config_sha):
            if args.json:
                _emit_event({"event": "building"})
            result = _execute_build(config_path, out_dir)
            result["diagnostics"] = discovery + result["diagnostics"]
            if not result["ok"]:
                _run_errors(result["diagnostics"], args.json)
                return result["exit_code"]
            if args.json:
                _emit_event({"event": "build_ok"})

    port_diagnostic = _check_port(args.host, args.port)
    if port_diagnostic is not None:
        _run_errors([port_diagnostic], args.json)
        return 2

    command = [
        sys.executable,
        "-m",
        "uvicorn",
        "main:app",
        "--host",
        args.host,
        "--port",
        str(args.port),
    ]
    try:
        process = subprocess.Popen(command, cwd=out_dir, stdout=sys.stderr, stderr=sys.stderr)
    except OSError as exc:
        diagnostic = _error(
            "FINN-E0051",
            "runtime",
            None,
            "cannot start server: {}".format(exc),
            hint="ensure fastapi and uvicorn are installed",
        )
        _run_errors([diagnostic], args.json)
        return 2

    probe_host = (
        "127.0.0.1" if args.host in ("0.0.0.0", "", "::") else args.host
    )
    if not _wait_for_port(probe_host, args.port, process):
        _terminate_child(process)
        diagnostic = _error(
            "FINN-E0051",
            "runtime",
            None,
            "server failed to start on {}:{}".format(args.host, args.port),
            hint="ensure fastapi and uvicorn are installed",
        )
        _run_errors([diagnostic], args.json)
        return 2

    if args.json:
        _emit_event(
            {
                "event": "listening",
                "host": args.host,
                "port": args.port,
                "pid": process.pid,
            }
        )
    elif not args.quiet:
        _print_banner(args.host, args.port, process.pid)

    stop = {"requested": False}

    def _handler(signum, frame):  # noqa: ARG001 - signal signature
        stop["requested"] = True

    previous = {}
    for signum in (signal.SIGINT, signal.SIGTERM):
        try:
            previous[signum] = signal.signal(signum, _handler)
        except (ValueError, OSError):  # pragma: no cover - non-main thread
            pass

    raw_exit_code = 0
    graceful = False
    try:
        while True:
            if stop["requested"]:
                _terminate_child(process)
                graceful = True
                raw_exit_code = 0
                break
            try:
                returncode = process.wait(timeout=0.2)
            except subprocess.TimeoutExpired:
                continue
            except KeyboardInterrupt:
                _terminate_child(process)
                graceful = True
                raw_exit_code = 0
                break
            raw_exit_code = returncode if returncode and returncode > 0 else 0
            break
    finally:
        for signum, handler in previous.items():
            try:
                signal.signal(signum, handler)
            except (ValueError, OSError):  # pragma: no cover - defensive
                pass

    # A graceful SIGINT/SIGTERM shutdown exits 0; any other non-zero child
    # return code is a runtime failure, which §5 maps to exit code 2.
    exit_code = 0 if graceful or not raw_exit_code else 2

    if args.json:
        _emit_event({"event": "stopped", "exitCode": raw_exit_code})
    elif raw_exit_code and not graceful and not args.quiet:
        sys.stderr.write(
            "FINN dev server exited with code {}\n".format(raw_exit_code)
        )
        sys.stderr.flush()
    return exit_code



def make_diagnostic(
    severity,
    code,
    stage=None,
    path=None,
    message="",
    hint=None,
    span=None,
):
    """Build one diagnostic dict (docs/cli-spec.md §4)."""

    return {
        "severity": severity,
        "code": code,
        "stage": stage,
        "path": path,
        "message": message,
        "hint": hint,
        "span": span,
    }


def _error(code, stage=None, path=None, message="", hint=None, span=None):
    return make_diagnostic("error", code, stage, path, message, hint, span)


def _warning(code, stage=None, path=None, message="", hint=None, span=None):
    return make_diagnostic("warning", code, stage, path, message, hint, span)


def _has_errors(diagnostics):
    return any(d.get("severity") == "error" for d in diagnostics)


def _exit_code(diagnostics):
    """Map diagnostics to the spec's exit code (§5)."""

    code = 0
    for diagnostic in diagnostics:
        if diagnostic.get("severity") != "error":
            continue
        mapped = _ERROR_EXIT.get(diagnostic.get("code"), 1)
        if mapped == 3:
            return 3
        if mapped == 2:
            code = 2
        elif mapped == 1 and code == 0:
            code = 1
    return code


def _supports_color(stream):
    if "NO_COLOR" in os.environ or "FINN_NO_COLOR" in os.environ:
        return False
    try:
        return bool(stream.isatty())
    except Exception:  # pragma: no cover - defensive
        return False


def _format_diagnostic(diagnostic, stream):
    word = diagnostic.get("severity") or "info"
    if _supports_color(stream) and word in _COLORS:
        word = _COLORS[word] + word + _RESET
    prefix = "{} [{}]".format(word, diagnostic.get("code"))
    if diagnostic.get("path"):
        prefix += " " + str(diagnostic["path"]) + ":"
    lines = [prefix + " " + str(diagnostic.get("message", ""))]
    if diagnostic.get("hint"):
        lines.append("  hint: " + str(diagnostic["hint"]))
    return "\n".join(lines)


def _print_diagnostics(diagnostics, stream=None):
    stream = stream or sys.stderr
    for diagnostic in diagnostics:
        stream.write(_format_diagnostic(diagnostic, stream) + "\n")
    try:
        stream.flush()
    except Exception:  # pragma: no cover - defensive
        pass


def _emit_json(document):
    sys.stdout.write(json.dumps(document, indent=2, ensure_ascii=False) + "\n")
    sys.stdout.flush()


def _emit_event(event):
    sys.stdout.write(
        json.dumps(event, separators=(",", ":"), ensure_ascii=False) + "\n"
    )
    sys.stdout.flush()


def _usage_error(message):
    diagnostic = _error(
        "FINN-E0091",
        None,
        None,
        message,
        hint="run 'finn --help' for usage",
    )
    _print_diagnostics([diagnostic], sys.stderr)
    return 3



def resolve_config(explicit=None, positional=None, cwd=None, env=None):
    """Resolve the config path (docs/cli-spec.md §3).

    Returns ``(path_or_None, diagnostics)``.
    """

    env = os.environ if env is None else env
    cwd = cwd or os.getcwd()
    diagnostics = []

    for candidate in (explicit, positional):
        if not candidate:
            continue
        path = os.path.abspath(os.path.expanduser(candidate))
        if os.path.isfile(path):
            return path, diagnostics
        diagnostics.append(
            _error(
                "FINN-E0011",
                "parse",
                None,
                "config file not found: {} (resolved to {})".format(
                    candidate, path
                ),
                hint="run 'finn init' or pass --config PATH",
            )
        )
        return None, diagnostics

    from_env = env.get("FINN_CONFIG")
    if from_env:
        path = os.path.abspath(os.path.expanduser(from_env))
        if os.path.isfile(path):
            return path, diagnostics
        diagnostics.append(
            _error(
                "FINN-E0011",
                "parse",
                None,
                "config file not found: {} (from FINN_CONFIG; resolved to "
                "{})".format(from_env, path),
                hint="run 'finn init' or pass --config PATH",
            )
        )
        return None, diagnostics

    default = os.path.join(cwd, "finn.json")
    if os.path.isfile(default):
        return default, diagnostics

    diagnostics.append(
        _error(
            "FINN-E0011",
            "parse",
            None,
            "no config file found (looked for finn.json)",
            hint="run 'finn init' or pass --config PATH",
        )
    )
    return None, diagnostics



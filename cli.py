class UsageError(Exception):
    """Raised instead of ``argparse`` calling ``sys.exit``."""


class _Parser(argparse.ArgumentParser):
    def error(self, message):
        raise UsageError(message)


def _build_parser():
    parser = _Parser(prog="finn", add_help=True, allow_abbrev=False)
    subparsers = parser.add_subparsers(dest="command")

    init = subparsers.add_parser("init", add_help=True, allow_abbrev=False)
    init.add_argument("target", nargs="?")
    init.add_argument(
        "--template",
        choices=("example", "minimal", "blank"),
        default="example",
    )
    init.add_argument("--force", action="store_true")
    init.add_argument("--name")
    init.add_argument("--json", action="store_true")

    build = subparsers.add_parser("build", add_help=True, allow_abbrev=False)
    build.add_argument("config_path", nargs="?")
    build.add_argument("--config")
    build.add_argument("--out")
    build.add_argument("--quiet", action="store_true")
    build.add_argument("--json", action="store_true")

    validate = subparsers.add_parser(
        "validate", add_help=True, allow_abbrev=False
    )
    validate.add_argument("config_path", nargs="?")
    validate.add_argument("--config")
    validate.add_argument("--json", action="store_true")

    run = subparsers.add_parser("run", add_help=True, allow_abbrev=False)
    run.add_argument("config_path", nargs="?")
    run.add_argument("--config")
    run.add_argument("--host", default="127.0.0.1")
    run.add_argument("--port", type=int, default=8000)
    run.add_argument("--no-build", dest="no_build", action="store_true")
    run.add_argument("--quiet", action="store_true")
    run.add_argument("--json", action="store_true")

    return parser


_HELP_TEXT = """usage: finn <command> [options]

Commands:
  init [TARGET_DIR]   Scaffold a new finn.json
  build [CONFIG]      Validate the config and emit the build directory
  run [CONFIG]        Build if stale, then serve the generated app
  validate [CONFIG]   Validate the config without writing anything

Global options:
  --version           Print the CLI version (add --json for JSON)
  --json              Machine-readable output (per command)
  -h, --help          Show this help

Environment:
  FINN_CONFIG, FINN_DB_PATH, NO_COLOR, FINN_NO_COLOR
"""

_COMMAND_HELP = {
    "init": """usage: finn init [TARGET_DIR] [--template example|minimal|blank]
                   [--force] [--name NAME] [--json]
""",
    "build": """usage: finn build [CONFIG] [--config PATH] [--out DIR] [--quiet] [--json]
""",
    "run": """usage: finn run [CONFIG] [--config PATH] [--host HOST]
                 [--port PORT] [--no-build] [--quiet] [--json]
""",
    "validate": """usage: finn validate [CONFIG] [--config PATH] [--json]
""",
}


def _dispatch(argv):
    if not argv:
        sys.stdout.write(_HELP_TEXT)
        return 0
    if argv[0] in ("-h", "--help"):
        sys.stdout.write(_HELP_TEXT)
        return 0
    if argv[0] == "help":
        if len(argv) > 1:
            if argv[1] not in _COMMAND_HELP:
                return _usage_error("unknown command {!r}".format(argv[1]))
            sys.stdout.write(_COMMAND_HELP[argv[1]])
            return 0
        sys.stdout.write(_HELP_TEXT)
        return 0
    if argv[0] == "--version" or (
        argv[0] == "--json" and len(argv) > 1 and argv[1] == "--version"
    ):
        if "--json" in argv:
            _emit_json(
                {"version": FINN_VERSION, "configSchema": CONFIG_SCHEMA}
            )
        else:
            sys.stdout.write("finn {}\n".format(FINN_VERSION))
        return 0

    parser = _build_parser()
    try:
        args = parser.parse_args(argv)
    except UsageError as exc:
        return _usage_error(str(exc))
    except SystemExit as exc:
        return int(exc.code or 0)

    if not getattr(args, "command", None):
        sys.stdout.write(_HELP_TEXT)
        return 0

    if args.command == "init":
        return _cmd_init(args)
    if args.command == "build":
        return _cmd_build(args)
    if args.command == "validate":
        return _cmd_validate(args)
    if args.command == "run":
        return _cmd_run(args)
    return _usage_error("unknown command {!r}".format(args.command))


def main(argv=None):
    """Run the CLI; return the process exit code."""

    argv = list(sys.argv[1:] if argv is None else argv)
    _quiet_package_loggers()

    def _interrupt(signum, frame):  # noqa: ARG001 - signal signature
        raise KeyboardInterrupt

    previous = {}
    for signum in (signal.SIGINT, signal.SIGTERM):
        try:
            previous[signum] = signal.signal(signum, _interrupt)
        except (ValueError, OSError):  # pragma: no cover - non-main thread
            pass

    try:
        return _dispatch(argv)
    except KeyboardInterrupt:
        return 130
    except BrokenPipeError:  # pragma: no cover - pipe closed by consumer
        return 0
    finally:
        for signum, handler in previous.items():
            try:
                signal.signal(signum, handler)
            except (ValueError, OSError):  # pragma: no cover - defensive
                pass


if __name__ == "__main__":
    sys.exit(main())

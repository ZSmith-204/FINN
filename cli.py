def _rel(path):
    try:
        return os.path.relpath(path)
    except (ValueError, OSError):  # pragma: no cover - defensive
        return path


def _display_dir(path):
    display = _rel(path)
    if display in ("", "."):
        return "./"
    if not display.endswith(os.sep):
        display += os.sep
    return display


def _human_bytes(size):
    if size < 1024:
        return "{} B".format(size)
    return "{:.1f} KB".format(size / 1024.0)


def _print_summary(result, config_path, out_dir, duration_ms):
    db_spec = result["db_spec"]
    api_spec = result["api_spec"]
    columns = sum(len(table.columns) for table in db_spec.tables.values())
    indexes = len(db_spec.indexes) + sum(
        len(table.indexes) for table in db_spec.tables.values()
    )
    operations = sum(
        len(endpoint.operations) for endpoint in api_spec.endpoints.values()
    )

    lines = [
        "Built {} \u2192 {}  ({:.1f}s)".format(
            _rel(config_path), _display_dir(out_dir), duration_ms / 1000.0
        ),
        "  tables: {}   columns: {}   indexes: {}   views: {}".format(
            len(db_spec.tables), columns, indexes, len(db_spec.views)
        ),
        "  endpoints: {}   operations: {}".format(
            len(api_spec.endpoints), operations
        ),
        "  database: {} ({})".format(
            _rel(result["db_path"]),
            "created" if result["db_created"] else "updated",
        ),
        "  artifacts:",
    ]
    for artifact in result["artifacts"]:
        lines.append(
            "    {:<24} {:>9}  {}".format(
                _rel(artifact["path"]),
                _human_bytes(artifact["bytes"]),
                artifact["action"],
            )
        )
    manifest_path = result["manifest_path"]
    lines.append(
        "    {:<24} {:>9}  {}".format(
            _rel(manifest_path),
            _human_bytes(result["manifest_bytes"]),
            result["actions"][".finn-build.json"],
        )
    )
    sys.stdout.write("\n".join(lines) + "\n")
    sys.stdout.flush()


def _build_json_document(result, config_path, out_dir, duration_ms):
    warnings = [
        diagnostic
        for diagnostic in result["diagnostics"]
        if diagnostic.get("severity") != "error"
    ]
    return {
        "ok": True,
        "config": _rel(config_path),
        "outDir": _rel(out_dir),
        "artifacts": [
            {
                "path": _rel(artifact["path"]),
                "bytes": artifact["bytes"],
                "action": artifact["action"],
            }
            for artifact in result["artifacts"]
        ],
        "db": {
            "path": _rel(result["db_path"]),
            "created": result["db_created"],
        },
        "diagnostics": warnings,
        "durationMs": duration_ms,
    }


def _emit_failure(
    diagnostics, json_mode, config_path=None, out_dir=None, duration_ms=None
):
    if json_mode:
        document = {"ok": False, "diagnostics": diagnostics}
        if config_path is not None:
            document["config"] = _rel(config_path)
        if out_dir is not None:
            document["outDir"] = _rel(out_dir)
        if duration_ms is not None:
            document["durationMs"] = duration_ms
        _emit_json(document)
    else:
        _print_diagnostics(diagnostics, sys.stderr)



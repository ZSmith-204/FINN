def _quiet_package_loggers():
    """Keep substrate package logs off stderr; the CLI emits diagnostics.

    The ``api``/``database`` packages log some warnings that the CLI already
    surfaces as diagnostics (for example FINN-W0002).  Suppressing them keeps
    ``--json`` output a single document on stdout with an empty stderr.
    """

    for name in ("api", "database"):
        package_logger = logging.getLogger(name)
        if not any(
            isinstance(handler, logging.NullHandler)
            for handler in package_logger.handlers
        ):
            package_logger.addHandler(logging.NullHandler())
        package_logger.propagate = False


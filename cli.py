def _utc_timestamp():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _file_record(path, display_name):
    with open(path, "rb") as handle:
        data = handle.read()
    return {
        "file": display_name,
        "sha256": hashlib.sha256(data).hexdigest(),
        "bytes": len(data),
    }


def _ensure_generated_header(path):
    """Prepend the FINN-owned header to ``path`` if it is missing (idempotent)."""

    with open(path, "r", encoding="utf-8") as handle:
        text = handle.read()
    if text.startswith(GENERATED_HEADER):
        return
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(GENERATED_HEADER)
        handle.write(text)


def _db_filename_problem(db_filename):
    """Return True when ``db_filename`` escapes the build directory (§7)."""

    if not db_filename or db_filename in (".", ".."):
        return True
    if os.path.isabs(db_filename):
        return True
    return any(part == ".." for part in Path(db_filename).parts)


def _execute_build(config_path, out_dir):
    """Run the full build pipeline; return a result dict (never raises)."""

    stages = _stage_config(config_path)
    diagnostics = list(stages["diagnostics"])
    result = {
        "ok": False,
        "exit_code": stages["exit_code"] or 1,
        "diagnostics": diagnostics,
        "stages": stages,
        "out_dir": out_dir,
    }
    if stages["exit_code"] != 0 or _has_errors(diagnostics):
        return result

    db_spec = stages["db_spec"]
    api_spec = stages["api_spec"]
    config_dir = os.path.dirname(os.path.abspath(config_path))
    db_filename = os.environ.get("FINN_DB_PATH") or db_spec.file or "finn.db"
    if _db_filename_problem(db_filename):
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                db_filename,
                "database filename must be a relative path inside the build "
                "directory (got {!r})".format(db_filename),
                hint=(
                    "set FINN_DB_PATH or database.file to a relative filename "
                    "such as 'finn.db' or 'data/app.db'"
                ),
            )
        )
        result["exit_code"] = 2
        return result
    db_path = os.path.join(out_dir, db_filename)
    if not os.path.realpath(db_path).startswith(os.path.realpath(out_dir)):
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                db_filename,
                "database path resolves outside the build directory: "
                "{}".format(db_path),
                hint=(
                    "set FINN_DB_PATH or database.file to a relative filename "
                    "inside the build directory"
                ),
            )
        )
        result["exit_code"] = 2
        return result
    db_py_path = os.path.join(out_dir, "DB.py")
    main_path = os.path.join(out_dir, "main.py")
    api_path = os.path.join(out_dir, "API.py")
    manifest_path = os.path.join(out_dir, ".finn-build.json")

    main_existed = os.path.exists(main_path)
    api_existed = os.path.exists(api_path)
    db_py_existed = os.path.exists(db_py_path)
    db_existed = os.path.exists(db_path)
    manifest_existed = os.path.exists(manifest_path)

    # Stage 4: emit the generated sources before touching the database so a
    # static-target error leaves no partial build behind.
    try:
        os.makedirs(out_dir, exist_ok=True)
    except OSError as exc:
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                out_dir,
                "cannot create output directory: {}".format(exc),
            )
        )
        result["exit_code"] = 2
        return result

    try:
        generate(out_dir, api_spec, base_dir=config_dir)
    except ConfigError as exc:
        diagnostics.append(
            _error("FINN-E0031", "semantic", exc.path, exc.message)
        )
        result["exit_code"] = 1
        return result
    except OSError as exc:
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                out_dir,
                "cannot write generated sources: {}".format(exc),
            )
        )
        result["exit_code"] = 2
        return result
    except Exception as exc:  # pragma: no cover - defensive
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                out_dir,
                "unexpected failure writing generated sources: {}".format(
                    exc
                ),
            )
        )
        result["exit_code"] = 2
        return result

    try:
        for path in (main_path, api_path):
            _ensure_generated_header(path)
    except OSError as exc:
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                path,
                "cannot write generated source header: {}".format(exc),
            )
        )
        result["exit_code"] = 2
        return result

    try:
        with open(db_py_path, "w", encoding="utf-8") as handle:
            handle.write(GENERATED_HEADER)
            handle.write(
                render_db_module(db_spec, db_filename=db_filename)
            )
    except OSError as exc:
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                db_py_path,
                "cannot write DB.py: {}".format(exc),
            )
        )
        result["exit_code"] = 2
        return result

    # Stage 5: create/verify the database.
    try:
        db_created = bootstrap(db_path, db_spec)
    except SchemaConflictError as exc:
        diagnostics.append(
            _error(
                "FINN-E0042",
                "build",
                exc.path,
                exc.message,
                hint=(
                    "remove the conflicting database, or change the config "
                    "to match the on-disk schema"
                ),
            )
        )
        result["exit_code"] = 2
        return result
    except sqlite3.Error as exc:
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                db_path,
                "database bootstrap failed: {}".format(exc),
            )
        )
        result["exit_code"] = 2
        return result
    except OSError as exc:
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                db_path,
                "cannot create database: {}".format(exc),
            )
        )
        result["exit_code"] = 2
        return result
    except ConfigError as exc:
        diagnostics.append(
            _error("FINN-E0031", "semantic", exc.path, exc.message)
        )
        result["exit_code"] = 1
        return result
    except Exception as exc:  # pragma: no cover - defensive
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                db_path,
                "unexpected database build failure: {}".format(exc),
            )
        )
        result["exit_code"] = 2
        return result

    # Stage 6: manifest.
    artifact_names = ["main.py", "API.py", "DB.py", db_filename]
    try:
        records = [
            _file_record(os.path.join(out_dir, name), name)
            for name in artifact_names
        ]
    except OSError as exc:
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                out_dir,
                "cannot hash build artifacts: {}".format(exc),
            )
        )
        result["exit_code"] = 2
        return result

    manifest = {
        "finnVersion": FINN_VERSION,
        "configSha256": hashlib.sha256(stages["raw"]).hexdigest(),
        "builtAt": _utc_timestamp(),
        "artifacts": records,
        "db": {"file": db_filename, "created": bool(db_created)},
    }
    try:
        with open(manifest_path, "w", encoding="utf-8") as handle:
            handle.write(json.dumps(manifest, indent=2) + "\n")
    except OSError as exc:
        diagnostics.append(
            _error(
                "FINN-E0041",
                "build",
                manifest_path,
                "cannot write build manifest: {}".format(exc),
            )
        )
        result["exit_code"] = 2
        return result

    actions = {
        "main.py": "created" if not main_existed else "updated",
        "API.py": "created" if not api_existed else "updated",
        "DB.py": "created" if not db_py_existed else "updated",
        db_filename: "created" if not db_existed else "updated",
        ".finn-build.json": "created" if not manifest_existed else "updated",
    }

    artifacts = []
    for name in artifact_names:
        path = os.path.join(out_dir, name)
        artifacts.append(
            {
                "path": path,
                "bytes": os.path.getsize(path),
                "action": actions[name],
            }
        )

    result.update(
        {
            "ok": True,
            "exit_code": 0,
            "diagnostics": diagnostics,
            "db_spec": db_spec,
            "api_spec": api_spec,
            "db_path": db_path,
            "db_filename": db_filename,
            "db_created": bool(db_created),
            "artifacts": artifacts,
            "actions": actions,
            "manifest_path": manifest_path,
            "manifest_bytes": os.path.getsize(manifest_path),
            "config_dir": config_dir,
            "raw": stages["raw"],
        }
    )
    return result


